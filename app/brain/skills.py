_SKILLS = {
    I.ORDER_STATUS: _ORDER_STATUS,
    I.PRODUCT_INFO: _PRODUCT_INFO,
    I.FAQ: _FAQ,
    I.CANCEL_ORDER: _CANCEL_ORDER,
    I.REFUND_RETURN: _REFUND_RETURN,
    I.DISCOUNT: _DISCOUNT,
    I.UNRECOGNIZED: _UNRECOGNIZED,
}


def skill_for(intent: str) -> str:
    return _SKILLS.get(intent, _UNRECOGNIZED)


def system_blocks(intent: str, extra_system: str = "") -> list:
    """The per-turn system param: [CORE (cached), skill (cached), volatile extras (uncached)].

    Cache layout (prefix match; tools render before system):
      breakpoint 1 — after CORE: caches tool schemas + core persona (stable across ALL turns)
      breakpoint 2 — after the intent's playbook: stable across turns of the same intent
      extras (lessons/style/tone/memory/products) change per turn → after the last breakpoint.
    """
    blocks = [
        {"type": "text", "text": CORE, "cache_control": {"type": "ephemeral"}},
        {"type": "text", "text": skill_for(intent), "cache_control": {"type": "ephemeral"}},
    ]
    if extra_system:
        blocks.append({"type": "text", "text": extra_system})
    return blocks
